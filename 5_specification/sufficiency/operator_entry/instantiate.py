#!/usr/bin/env python3
"""Path A binding generation rule v1 (docs/OPERATOR_ENTRY_PROTOCOL.md section 3).

From one recorded ATen call (overload, arguments with tensor pre-state copies) and one (contract, profile) candidate,
write into a scratch copy of the specification tree:
  corpus/calls/<name>.py            the measured call: the same overload under flag_gems.use_gems(), on the recorded
                                    tensors (each tensor a named input), non-tensor arguments exactly as recorded
  corpus/calls/<name>_inputs.py     input generators returning the recorded tensors (same size, stride and values)
  corpus/call_bindings/<name>.json  the binding plan: /op = aten.<base name>, every positional argument and every
                                    non-default keyword in the contract's ATen-call format (tensors from the recorded
                                    pre-state, others as literals); the single returned tensor bound to the profile's
                                    single output; every tensor argument declared unchanged
  validated/bindings|calls          retained copies (evaluation device inside the scratch tree only)
  corpus/measure_cases/<name>.json  the declaration (contract mode)

Refusals (raised as Refuse with the stage name) instead of guesses: a mutable / out overload, a non-tensor argument the
contract format cannot carry, a nested tensor container, a return that is not one tensor, a profile with more than one
output, a measured output whose kind is not numeric or Boolean.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import torch

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import core_aten  # noqa: E402  (enc, non_default_kwargs, Skip)

RULE = "operator_entry.instantiate v1"
FLAGGEMS_EXCLUDE = ("copy_", "to_copy", "index")   # FlagGems function names (aten copy_, _to_copy, index.Tensor)


class Refuse(Exception):
    def __init__(self, stage, why):
        super().__init__(f"{stage}: {why}")
        self.stage, self.why = stage, why


def overload(op: str):
    ns, name, ov = op.split(".") if op.count(".") == 2 else (op.split(".") + ["default"])[:3]
    return getattr(getattr(getattr(torch.ops, ns), name), ov)


def _template(x, tensors, path):
    """Replace tensors by {"__tensor__": name}; tensors gets name -> (json pointer, tensor)."""
    if isinstance(x, torch.Tensor):
        name = f"a{len(tensors)}"
        tensors[name] = (path, x)
        return {"__tensor__": name}
    if isinstance(x, (list, tuple)):
        if any(isinstance(v, torch.Tensor) for v in x) and not all(isinstance(v, torch.Tensor) or v is None for v in x):
            raise Refuse("argument encoding", "mixed tensor / non-tensor container")
        return type(x)(_template(v, tensors, f"{path}/{i}") for i, v in enumerate(x))
    if isinstance(x, dict):
        raise Refuse("argument encoding", "dictionary argument")
    return x


def _literals(x, path, out):
    """Input-map entries for every non-tensor leaf (in the contract's encoding)."""
    if isinstance(x, dict) and "__tensor__" in x:
        return
    if isinstance(x, (list, tuple)) and any(isinstance(v, dict) and "__tensor__" in v for v in x):
        for i, v in enumerate(x):
            if v is None:
                out.append({"target": f"{path}/{i}", "literal": None, "basis": "recorded argument"})
            else:
                _literals(v, f"{path}/{i}", out)
        return
    try:
        out.append({"target": path, "literal": core_aten.enc(x), "basis": "recorded argument value"})
    except core_aten.Skip as err:
        raise Refuse("argument encoding", str(err)) from None


def generate(spec: Path, name: str, op: str, values_pt: Path, contract: dict, profile: str, runtime: dict,
             exclude=FLAGGEMS_EXCLUDE):
    """Write the five files; return the declaration path. contract: loaded contract data (dict)."""
    fn = overload(op)
    schema = fn._schema
    if schema.is_mutable or any(a.alias_info is not None and a.alias_info.is_write for a in schema.arguments):
        raise Refuse("state mapping", "mutable or out overload (state semantics not generated by rule v1)")
    if len(schema.returns) != 1 or str(schema.returns[0].type) != "Tensor":
        raise Refuse("output mapping", f"return type {[str(r.type) for r in schema.returns]} is not one tensor")
    from kernel_spec.schema import profile_outputs
    outs = profile_outputs(contract, profile)
    if len(outs) != 1:
        raise Refuse("output mapping", f"profile {profile} has {len(outs)} outputs")
    (field, info), = outs.items()
    if info.get("kind") == "discrete" or info.get("guarantee") not in ("exact", "rigorous_enclosure"):
        raise Refuse("output mapping", f"output {field} kind {info.get('kind')} is not a measurable numeric target")
    rec = torch.load(values_pt, map_location="cuda", weights_only=False)
    args, kwargs = rec["args"], core_aten.non_default_kwargs(fn, rec["kwargs"])
    tensors = {}
    t_args = [_template(v, tensors, f"/args/{i}") for i, v in enumerate(args)]
    t_kwargs = {k: _template(v, tensors, f"/kwargs/{k}") for k, v in kwargs.items()}
    input_map = [{"target": "/op", "literal": "aten." + schema.name.split("::")[1],
                  "basis": f"recorded overload {op} (rule {RULE})"}]
    for tname, (path, t) in tensors.items():
        input_map.append({"target": path, "source": f"/tensor_arguments/{tname}/before", "conversion": "tensor_record"})
    for i, v in enumerate(t_args):
        _literals(v, f"/args/{i}", input_map)
    for k, v in t_kwargs.items():
        _literals(v, f"/kwargs/{k}", input_map)
    if not t_args:
        input_map.append({"target": "/args", "literal": [], "basis": "no positional argument recorded"})
    if not t_kwargs:
        input_map.append({"target": "/kwargs", "literal": {}, "basis": "no non-default keyword argument recorded"})
    # files
    calls, binds = spec / "corpus/calls", spec / "corpus/call_bindings"
    data = spec / "corpus/calls" / f"{name}_values.pt"
    torch.save({"args": t_args, "kwargs": t_kwargs, "tensors": {k: t for k, (_, t) in tensors.items()}}, data)
    plan_id = f"path_a.{name}"
    call_src = CALL_TEMPLATE.format(op=op, rule=RULE, data=data.name, exclude=tuple(exclude))
    (calls / f"{name}.py").write_text(call_src)
    (calls / f"{name}_inputs.py").write_text(INPUTS_TEMPLATE.format(data=data.name) + "".join(
        f"\n\ndef {t}(seed, shape, dtype):\n    return _get({t!r})\n" for t in tensors))
    plan = {"schema": "triton-call-binding-v1", "id": plan_id, "status": "reviewed", "unresolved": [],
            "generated_by": RULE,
            "subject": {"library": "FlagGems", "version": runtime["version"], "callable": f"{op} under flag_gems.use_gems()",
                        "runtime_package": runtime, "boundary": "one recorded ATen call at the dispatch boundary",
                        "measure_call": f"../calls/{name}.py:call"},
            "launch_scope": "all_triton_launches_within_call",
            "tasks": [{"id": "op", "contract": contract["id"], "profile": profile,
                       "task_statement": f"The {contract['id']} profile {profile} applied to the recorded {op} call "
                                         f"(no task choice: the profile requires none).",
                       "input_map": input_map,
                       "output_map": [{"target": f"/{field}", "source": "/returns/out", "conversion": "tensor_record",
                                       "measure_output": "out"}]}],
            "state_map": [{"argument": t, "effect": "unchanged"} for t in tensors]}
    text = json.dumps(plan, indent=2) + "\n"
    (binds / f"{name}.json").write_text(text)
    (spec / "validated/bindings" / f"{plan_id}.json").write_text(text)
    (spec / "validated/calls" / f"{plan_id}.py").write_text(call_src)
    tdt = {torch.float32: "float32", torch.bfloat16: "bfloat16", torch.float16: "float16", torch.float64: "float64"}
    decl = {"call": f"../calls/{name}.py:call",
            "inputs": {t: {"state": f"../calls/{name}_inputs.py:{t}", "shape": list(x.shape),
                           "dtype": tdt.get(x.dtype, str(x.dtype).replace("torch.", ""))} for t, (_, x) in tensors.items()},
            "compare": {"mode": "contract", "measure": ["out"], "binding_plan": f"../call_bindings/{name}.json",
                        "specification_root": "../.."},
            "units": {"development": 1, "confirmation": 2, "seed_offset": 0},
            "alpha": 0.05,
            "budget": {"cpu_seconds": 600, "gpu_seconds": 600, "case_timeout": 600, "max_units": 3},
            "rule_classes": {"fixed_mean": ["R1", "R5"], "aligned": ["R2", "R3"]},
            "multiplicity": "Holm within each rule class",
            "reference_classes_allowed": ["complete_composed"],
            "resolution": {"ulp_fraction": 0.125, "max_level": 3}}
    dpath = spec / "corpus/measure_cases" / f"{name}.json"
    dpath.write_text(json.dumps(decl, indent=1))
    return dpath


