TARGET_SHA = "441bcc9703afec7c274028d168a486f7d79ace360d7b4551d4e9fef2ca6c7c72"
TARGET_LEFT_SHAPE = (64, 200064)


def canonical(value: object) -> str:
    return hashlib.sha256(json.dumps(
        value, sort_keys=True, separators=(",", ":")
    ).encode()).hexdigest()


class MMRepair:
    def __init__(self, modules: list[Any], mode: str, permutation: torch.Tensor | None = None) -> None:
        self.modules = modules
        self.mode = mode
        self.permutation = permutation
        self.restores = []
        self.calls = 0
        self.local = None
        self.local_vector = None
        self.repair_vector = None
        self.natural_vector = None

    def __enter__(self) -> "MMRepair":
        seen = set()
        for module in self.modules:
            namespace = getattr(module, "extern_kernels", None)
            if namespace is None or id(namespace) in seen:
                continue
            seen.add(id(namespace)); original = namespace.mm

            def wrapped(*args: Any, _original: Any = original, **kwargs: Any) -> Any:
                _, _, digest = _source_identity()
                # The frozen release may be regenerated by a newer Inductor
                # patcher and therefore carry a different source digest.  The
                # semantic endpoint is still uniquely identified for this
                # fixed seq64 Phi campaign by its exact dX left operand shape.
                if digest != TARGET_SHA and tuple(args[0].shape) != TARGET_LEFT_SHAPE:
                    return _original(*args, **kwargs)
                result = _original(*args, **kwargs)
                candidate = kwargs.get("out", result)
                if not isinstance(candidate, torch.Tensor):
                    raise RuntimeError("target MM has no tensor output")
                before = candidate.detach().clone()
                if self.mode == "SHAM":
                    replacement = torch.mm(args[0], args[1])
                elif self.mode == "REPAIR_FP32_CAST_BF16":
                    replacement = fp32_external_reference("mm", args, kwargs)
                elif self.mode == "REPAIR_PERMUTE":
                    if self.permutation is None or before.ndim != 2:
                        raise RuntimeError("permuted Phi MM repair needs a row permutation")
                    replacement = fp32_external_reference("mm", args, kwargs)
                else:
                    raise ValueError(self.mode)
                cast = replacement.to(candidate.dtype)
                natural_delta = before.float() - cast.float()
                self.natural_vector = natural_delta.detach().float().cpu().numpy().reshape(-1).copy()
                if self.mode == "REPAIR_PERMUTE":
                    if int(self.permutation.numel()) != int(natural_delta.shape[0]):
                        raise RuntimeError("Phi MM permutation row count differs")
                    shuffled = natural_delta.index_select(0, self.permutation.to(natural_delta.device))
                    delivered = cast.float() + shuffled
                    candidate.copy_(delivered.to(candidate.dtype))
                    delta = before.float() - delivered
                else:
                    candidate.copy_(cast)
                    delta = natural_delta
                candidate_error = before.float() - replacement.float()
                repair_error = cast.float() - replacement.float()
                self.local = {
                    "coordinates": delta.numel(),
                    "changed_coordinates": int(torch.count_nonzero(delta).item()),
                    "max_abs": float(delta.abs().max().item()),
                    "l2": float(torch.linalg.vector_norm(delta).item()),
                    "candidate_vs_fp32_l2": float(torch.linalg.vector_norm(candidate_error).item()),
                    "repair_vs_fp32_l2": float(torch.linalg.vector_norm(repair_error).item()),
                    "candidate_vs_fp32_max_abs": float(candidate_error.abs().max().item()),
                    "repair_vs_fp32_max_abs": float(repair_error.abs().max().item()),
                }
                # The v2.1 formation capture consumes this complete endpoint
                # residual.  Keep only the current state in host memory; the
                # reducer stores a digest/Gram, not raw vectors.
                self.local_vector = delta.detach().float().cpu().numpy().reshape(-1)
                self.repair_vector = cast.detach().float().cpu().numpy().reshape(-1)
                self.calls += 1
                return result

            namespace.mm = wrapped
            self.restores.append((namespace, original))
        return self

    def __exit__(self, *unused: Any) -> None:
        del unused
        for namespace, original in self.restores:
            namespace.mm = original
        if self.calls != 1:
            raise RuntimeError(f"target repair executed {self.calls} times")


def run(model: torch.nn.Module, candidate: Any, values: torch.Tensor,
        seed: int, modules: list[Any], mode: str | None) -> tuple[dict[str, str], dict[str, Any] | None]:
    torch.manual_seed(seed); torch.cuda.manual_seed_all(seed)
    model.zero_grad(set_to_none=True)
    observer = MMRepair(modules, mode) if mode else None
    if observer:
        with observer:
            loss = candidate(values); loss.backward()
    else:
        loss = candidate(values); loss.backward()
    torch.cuda.synchronize(values.device)
    return {"loss": tensor_digest(loss), "gradients": gradient_digest(model)}, \
        observer.local if observer else None


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--states", type=int, default=2)
    parser.add_argument("--device", default="cuda:0")
    parser.add_argument("--output", type=Path, default=ROOT / "results/coverage/cases/phi4_seq64_lmhead_dx_repair_pilot.json")
    args = parser.parse_args()
    bank = json.loads((ROOT / "results/coverage/phi4_seq64_input_bank.json").read_text())
    states = bank.get("states", bank.get("records"))[:args.states]
    release = ROOT / "results/coverage/runtime_releases/phi4_seq64_r1"
    capture = json.loads((release / "capture.json").read_text())
    device = torch.device(args.device)
    configure_candidate_runtime(24000)
    model = load_model("phi", Path("/data1/tzh/models/microsoft/Phi-4-mini-instruct"), device)
    start = len(PyCodeCache.modules)
    candidate = torch.compile(LossStep(model), backend="inductor", fullgraph=False, dynamic=False)
    warm = torch.tensor([states[0]["token_ids"]], dtype=torch.long, device=device)
    model.zero_grad(set_to_none=True); candidate(warm).backward(); torch.cuda.synchronize(device)
    modules = list(PyCodeCache.modules[start:])
    validate_release(wrapper_modules(modules), capture)
    rows = []
    carrier = StreamingGramAccumulator(
        Path("/data1/tzh/cache/kernel_analyzer_contrasts/phi64_lmhead_dx_repair"),
        "model.norm.weight", chunk_elements=1_048_576,
    )
    for index, state in enumerate(states):
        values = torch.tensor([state["token_ids"]], dtype=torch.long, device=device)
        seed = 24000 + index
        standard, _ = run(model, candidate, values, seed, modules, None)
        standard_grads = {name: parameter.grad.detach().clone()
                          for name, parameter in model.named_parameters()
                          if parameter.grad is not None}
        sham, sham_local = run(model, candidate, values, seed, modules, "SHAM")
        if sham != standard or not sham_local or sham_local["changed_coordinates"] != 0:
            raise RuntimeError("same-dtype sham changed endpoints")
        repair, repair_local = run(
            model, candidate, values, seed, modules, "REPAIR_FP32_CAST_BF16"
        )
        changed = []
        total_sq = 0.0
        for name, parameter in model.named_parameters():
            if parameter.grad is None:
                continue
            delta = parameter.grad.float() - standard_grads[name].float()
            norm = float(torch.linalg.vector_norm(delta).item())
            if norm:
                changed.append({"name": name, "l2": norm,
                                "max_abs": float(delta.abs().max().item())})
                total_sq += norm * norm
            if name == "model.norm.weight":
                final_norm_delta = standard_grads[name].float() - parameter.grad.float()
                carrier.add_array(str(state.get("state_id", index)), final_norm_delta.cpu().numpy())
        rows.append({
            "state_id": str(state.get("sequence_id", state.get("state_id", index))),
            "standard_endpoint": standard, "sham_endpoint": sham,
            "repair_endpoint": repair, "sham_local": sham_local,
            "repair_local": repair_local, "changed_parameter_count": len(changed),
            "changed_parameters": changed,
            "all_parameter_gradient_delta_l2": total_sq ** 0.5,
        })
        del standard_grads, values
        torch.cuda.empty_cache()
        print(json.dumps({"event": "STATE_COMPLETE", "state": index,
                          "local_changed": repair_local["changed_coordinates"],
                          "parameters_changed": len(changed)}), flush=True)
    cast_null = all(row["repair_local"]["changed_coordinates"] == 0 for row in rows)
    carrier_certificate = carrier.finalize(
        bootstrap_draws=4000, seed=14031, cleanup=True,
    )
    local_repair_improves = all(
        row["repair_local"]["repair_vs_fp32_l2"]
        < row["repair_local"]["candidate_vs_fp32_l2"] for row in rows
    )
    payload = {
        "schema": "kernel-analyzer-phi64-lmhead-dx-repair-pilot-v1",
        "status": "CAST_NULL_NOT_CAUSALLY_REPAIRABLE" if cast_null
                  else "LOCAL_REPAIR_CHANGES_RUNTIME_CANDIDATE",
        "candidate_id": "phi4_seq64_backward_497_output",
        "intervention": "FP32 MM followed by required BF16 ABI cast",
        "states": rows,
        "local_repair_improves_every_state": local_repair_improves,
        "final_norm_weight_carrier": carrier_certificate,
        "claim_boundary": "Pilot T2 only; no T3/T4 claim.",
    }
    payload["result_sha256"] = canonical(payload)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    print(json.dumps({"status": payload["status"], "output": str(args.output)}))


if __name__ == "__main__":
    main()
