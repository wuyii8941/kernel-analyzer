#!/usr/bin/env python3
"""Realistic workload of the tolerance study (protocol.md section 2): full fine-tuning of Qwen2.5-0.5B-Instruct on
alpaca-cleaned, reproducing the settings of torchtune's official recipe config
`recipes/configs/qwen2_5/0.5B_full_single_device.yaml` (fetched 2026-10-12, copy in .cache/upstream/realism_20261012):

    dtype bf16 (parameters, gradients and optimizer states in bf16 -- "pure bf16")
    optimizer torch.optim.AdamW(fused=True, lr=2e-5)  (betas, eps, weight_decay: PyTorch defaults)
    batch_size 2, gradient_accumulation_steps 8, epochs 1, shuffle True, no gradient clipping, no compile
    loss: cross entropy on the response tokens only (torchtune's alpaca dataset default train_on_input=False)

This script uses Hugging Face transformers for the model and its chat template instead of torchtune itself (not
installed); differences: the loss is the token-mean over the accumulation window, sequences are truncated at 1024
tokens (torchtune: max_seq_len null; alpaca-cleaned rarely exceeds it), the model is the HF checkpoint.

Variants (one mechanism changed at a time, protocol section 4):
    --master fp32                   an fp32 master copy of the parameters and fp32 optimizer states, bf16 compute (the
                                    reference precision of the parameter and state storage)
    --optimizer adamw_fused         torch.optim.AdamW(fused=True): torchtune's default (ATen fused kernel)
                adamw_compiled      torch.compile(AdamW(foreach=True).step): PyTorch's "compiling the optimizer" recipe
                                    (Triton kernels generated by Inductor)
                adamw_torchao_sr    torchao.optim._AdamW(bf16_stochastic_round=True): stochastic rounding of the
                                    bf16 parameter update (states stay bf16, rounded to nearest)
                radam_compiled / radam_eager   torch.optim.RAdam (default betas), compiled step / eager
    --param-dtype bf16|fp32
    --ema none|all                  "all": three EMAs of the weights (decay 0.999) side by side --
                                    torch.optim.swa_utils.AveragedModel(get_ema_multi_avg_fn(0.999)) in the model dtype,
                                    timm 1.0.30 ModelEmaV3(decay=0.999) in the model dtype (the released timm; installed
                                    in .cache/pydeps/timm_1_0_30), and an fp32 EMA (reference precision)

Captures (``--capture-steps``): before the optimizer step t, the pre-declared coordinates of the pre-declared tensors
(``CAPTURE_TENSORS``; ``capture_index``) of parameter, gradient and optimizer state, written to ``--out``.
"""
from __future__ import annotations

import argparse
import json
import math
import os
import time
from pathlib import Path

import numpy as np
import torch

MODEL = "Qwen/Qwen2.5-0.5B-Instruct"
DATA_GLOB = "datasets--yahma--alpaca-cleaned/snapshots/*/alpaca_data_cleaned.json"
CAPTURE_TENSORS = [f"model.layers.{i}.{n}" for i in (0, 11, 23) for n in
                   ("self_attn.q_proj.weight", "self_attn.q_proj.bias", "mlp.down_proj.weight", "input_layernorm.weight")]
CAPTURE_COORDS = 65536          # per tensor (all coordinates when the tensor is smaller)
CAPTURE_INDEX_SEED = 20261012   # fixed before any run (protocol section 3)
EVAL_N = 256                    # held-out examples (the last EVAL_N of the shuffled-by-a-fixed-seed list)


def capture_index(numel: int) -> np.ndarray:
    rng = np.random.default_rng(CAPTURE_INDEX_SEED + numel)
    if numel <= CAPTURE_COORDS:
        return np.arange(numel)
    return np.sort(rng.choice(numel, CAPTURE_COORDS, replace=False))


def load_examples(hf_home: str):
    import glob
    path = glob.glob(os.path.join(hf_home, "hub", DATA_GLOB))[0]
    data = json.loads(Path(path).read_text())
    order = np.random.default_rng(1).permutation(len(data))      # fixed split, independent of the run seed
    held = [data[i] for i in order[-EVAL_N:]]
    train = [data[i] for i in order[:-EVAL_N]]
    return train, held


def encode(tok, ex, max_len=1024):
    user = ex["instruction"] + (("\n\n" + ex["input"]) if ex.get("input") else "")
    prompt = tok.apply_chat_template([{"role": "user", "content": user}], tokenize=False, add_generation_prompt=True)
    full = prompt + ex["output"] + tok.eos_token
    p_ids = tok(prompt, add_special_tokens=False)["input_ids"]
    ids = tok(full, add_special_tokens=False)["input_ids"][:max_len]
    labels = [-100] * min(len(p_ids), len(ids)) + ids[len(p_ids):]
    return ids, labels[:len(ids)]


def batches(tok, examples, seed, batch_size):
    order = np.random.default_rng(seed).permutation(len(examples))
    for s in range(0, len(order) - batch_size + 1, batch_size):
        enc = [encode(tok, examples[i]) for i in order[s:s + batch_size]]
        n = max(len(e[0]) for e in enc)
        ids = torch.full((batch_size, n), tok.pad_token_id, dtype=torch.long)
        lab = torch.full((batch_size, n), -100, dtype=torch.long)
        att = torch.zeros((batch_size, n), dtype=torch.long)
        for j, (a, b) in enumerate(enc):
            ids[j, :len(a)] = torch.tensor(a)
            lab[j, :len(b)] = torch.tensor(b)
            att[j, :len(a)] = 1
        yield ids, lab, att


def token_loss_sum(model, ids, lab, att):
    logits = model(input_ids=ids, attention_mask=att).logits.float()
    shift, tgt = logits[:, :-1], lab[:, 1:]
    loss = torch.nn.functional.cross_entropy(shift.reshape(-1, shift.size(-1)), tgt.reshape(-1), ignore_index=-100,
                                             reduction="sum")
    return loss, int((tgt != -100).sum())


@torch.no_grad()
def evaluate(model, tok, held, batch_size=8):
    model.eval()
    tot, n = 0.0, 0
    for ids, lab, att in batches(tok, held, 0, batch_size):
        l, k = token_loss_sum(model, ids.cuda(), lab.cuda(), att.cuda())
        tot += float(l)
        n += k
    model.train()
    return tot / max(n, 1)


def make_optimizer(name, params, state_dtype, lr):
    if name == "adamw_fused":
        return torch.optim.AdamW(params, lr=lr, fused=True)
    if name == "adamw_compiled":
        return torch.optim.AdamW(params, lr=lr, foreach=True)
    if name == "adamw_torchao_sr":
        from torchao.optim import _AdamW
        return _AdamW(params, lr=lr, bf16_stochastic_round=True)
    if name in ("radam_compiled", "radam_eager"):
        return torch.optim.RAdam(params, lr=lr, foreach=True)
    raise ValueError(name)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, required=True)
    ap.add_argument("--steps", type=int, required=True)
    ap.add_argument("--optimizer", default="adamw_fused")
    ap.add_argument("--param-dtype", default="bf16")
    ap.add_argument("--state-dtype", default="bf16", choices=("bf16",))
    ap.add_argument("--master", default="none", choices=("none", "fp32"))
    ap.add_argument("--ema", default="none")
    ap.add_argument("--lr", type=float, default=2e-5)
    ap.add_argument("--capture-steps", default="")
    ap.add_argument("--eval-steps", default="")
    ap.add_argument("--init", default="", help="resume from a saved state (parameters + optimizer states)")
    ap.add_argument("--save-at", type=int, default=0, help="save parameters and optimizer state after this step")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    from transformers import AutoModelForCausalLM, AutoTokenizer

    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    hf_home = os.environ["HF_HOME"]
    tok = AutoTokenizer.from_pretrained(MODEL)
    pdtype = {"bf16": torch.bfloat16, "fp32": torch.float32}[a.param_dtype]
    model = AutoModelForCausalLM.from_pretrained(MODEL, dtype=pdtype).cuda()
    model.train()
    named = dict(model.named_parameters())
    position = {id(p): i for i, p in enumerate(model.parameters())}
    train, held = load_examples(hf_home)
    params = [p for p in model.parameters() if p.requires_grad]
    master = None
    if a.master == "fp32":                     # reference precision: fp32 master parameters and fp32 states
        master = [p.detach().float().clone().requires_grad_(True) for p in params]
        opt = make_optimizer(a.optimizer, master, "fp32", a.lr)
    else:
        opt = make_optimizer(a.optimizer, params, a.state_dtype, a.lr)
    step_fn = torch.compile(opt.step) if a.optimizer.endswith("_compiled") else opt.step
    emas = {}
    if a.ema == "all":
        import sys
        from torch.optim.swa_utils import AveragedModel, get_ema_multi_avg_fn
        sys.path.append(str(Path(__file__).resolve().parents[3] / ".cache" / "pydeps" / "timm_1_0_30"))
        from timm.utils.model_ema import ModelEmaV3
        emas["averaged_model"] = AveragedModel(model, multi_avg_fn=get_ema_multi_avg_fn(0.999), use_buffers=False)
        emas["timm_1_0_30"] = ModelEmaV3(model, decay=0.999)
        emas["fp32"] = [p.detach().float().clone() for p in model.parameters()]
    if a.init:
        st = torch.load(a.init, map_location="cuda", weights_only=False)
        with torch.no_grad():
            for p, v in zip(params, st["params"]):
                p.copy_(v)
            if master is not None:
                for m, v in zip(master, st.get("master") or st["params"]):
                    m.copy_(v.float())
        opt.load_state_dict(st["opt"]) if st.get("opt_kind") == a.optimizer + a.master + a.state_dtype else None
    capture_steps = {int(s) for s in a.capture_steps.split(",") if s}
    eval_steps = {int(s) for s in a.eval_steps.split(",") if s}
    log = []
    it = batches(tok, train, a.seed, 2)
    t0 = time.time()
    for step in range(1, a.steps + 1):
        tot_tokens, losses, micro = 0, [], []
        for _ in range(8):
            micro.append(next(it))
        tot_tokens = sum(int((lab[:, 1:] != -100).sum()) for _, lab, _ in micro)
        for ids, lab, att in micro:
            l, _ = token_loss_sum(model, ids.cuda(), lab.cuda(), att.cuda())
            (l / tot_tokens).backward()
            losses.append(float(l))
        if master is not None:
            for m, p in zip(master, params):
                m.grad = p.grad.detach().float()
        if step in capture_steps:
            cap = {"step": step, "seed": a.seed, "config": vars(a), "tensors": {}, "ema": {}}
            for ename, e in emas.items():   # EMA values before this step's update (after step - 1 updates)
                if ename == "fp32":
                    src = dict(zip([n for n, _ in model.named_parameters()], e))
                elif ename == "averaged_model":
                    src = dict(e.module.named_parameters())
                else:
                    src = dict(e.module.named_parameters())
                cap["ema"][ename] = {n: src[n].detach().reshape(-1)[torch.as_tensor(capture_index(src[n].numel()),
                                                                                     device=src[n].device)].cpu()
                                     for n in CAPTURE_TENSORS}
            for name in CAPTURE_TENSORS:
                p = named[name]
                q = p if master is None else master[position[id(p)]]
                idx = torch.as_tensor(capture_index(p.numel()), device=p.device)
                s = opt.state.get(q, {})
                cap["tensors"][name] = {
                    "index_numel": p.numel(),
                    "param": q.detach().reshape(-1)[idx].cpu(), "grad": (q.grad if q.grad is not None else p.grad
                                                                        ).detach().reshape(-1)[idx].cpu(),
                    "exp_avg": s["exp_avg"].reshape(-1)[idx].cpu() if "exp_avg" in s else None,
                    "exp_avg_sq": s["exp_avg_sq"].reshape(-1)[idx].cpu() if "exp_avg_sq" in s else None,
                    "state_step": float(s["step"]) if "step" in s else 0.0}
            torch.save(cap, out / f"capture_step{step:05d}.pt")
        step_fn()
        opt.zero_grad(set_to_none=True)
        if master is not None:
            with torch.no_grad():
                for m, p in zip(master, params):
                    p.copy_(m.to(p.dtype))
                    p.grad = None
        else:
            for p in params:
                p.grad = None
        if emas:
            emas["averaged_model"].update_parameters(model)
            emas["timm_1_0_30"].update(model, step=step)
            with torch.no_grad():
                for e32, p in zip(emas["fp32"], model.parameters()):
                    e32.lerp_(p.detach().float(), 1 - 0.999)
        rec = {"step": step, "train_loss": sum(losses) / tot_tokens, "tokens": tot_tokens,
               "seconds": round(time.time() - t0, 1)}
        if step in eval_steps:
            rec["eval_loss"] = evaluate(model, tok, held)
            if emas:
                rec["eval_loss_ema_averaged_model"] = evaluate(emas["averaged_model"].module, tok, held)
                rec["eval_loss_ema_timm_1_0_30"] = evaluate(emas["timm_1_0_30"].module, tok, held)
                saved = [p.detach().clone() for p in model.parameters()]
                with torch.no_grad():                         # the fp32 EMA evaluated in the model (bf16 compute)
                    for p, e32 in zip(model.parameters(), emas["fp32"]):
                        p.copy_(e32.to(p.dtype))
                rec["eval_loss_ema_fp32"] = evaluate(model, tok, held)
                with torch.no_grad():
                    for p, v in zip(model.parameters(), saved):
                        p.copy_(v)
        log.append(rec)
        if a.save_at and step == a.save_at:
            torch.save({"params": [p.detach().clone() for p in params],
                        "master": [m.detach().clone() for m in master] if master is not None else None,
                        "opt": opt.state_dict(), "opt_kind": a.optimizer + a.master + a.state_dtype},
                       out / f"state_step{step:05d}.pt")
    (out / "log.json").write_text(json.dumps({"config": vars(a), "log": log}, indent=1) + "\n")
    print(json.dumps(log[-1]))


if __name__ == "__main__":
    main()
